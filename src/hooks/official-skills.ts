export interface OfficialBatonSkill {
  name: string;
  content: string;
}

function skill(name: string, description: string, body: string[]): OfficialBatonSkill {
  return {
    name,
    content: [
      '---',
      `name: ${name}`,
      `description: ${description}`,
      '---',
      '',
      ...body,
      '',
    ].join('\n'),
  };
}

